/**
 * Obsidian 插件的构建配置：把 `src/main.ts` 打成 `bin/exports/main.js`，并把
 * `manifest.json`、`styles.css` 复制进交付包，最后同步到 vault 插件目录。
 *
 * 用法：
 *   npm run dev   监听编译（inline sourcemap，不压缩），每次成功后同步到插件目录
 *   npm run build 生产构建（压缩、不生成 sourcemap）
 *
 * `external` 必须带 Obsidian 运行时与 Node 内置模块：插件由 Obsidian 宿主加载，
 * 这些模块不能打进包里。Node 内置模块要写两种形式——`builtinModules` 里是不带前缀的
 * `fs`，源码里写的是 `node:fs`。
 */
import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import path from "node:path";
import { builtinModules } from "node:module";
import { fileURLToPath } from "node:url";
import { deployArtifacts } from "./deploy.mjs";

/** 项目根（本脚本在 `src/scripts/` 下）。 */
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
/** 交付包目录：`main.js` 产出到这里，manifest 与 styles 由构建时复制过来。 */
const exportDir = path.join(projectRoot, "bin", "exports");

/** 构建成功后把仓库里的源文件复制进交付包，保证交付包能整包安装或上传。 */
const copyExportAssets = {
	name: "copy-export-assets",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			fs.mkdirSync(exportDir, { recursive: true });
			for (const [from, to] of [
				["manifest.json", "manifest.json"],
				["src/styles.css", "styles.css"],
			]) {
				const source = path.join(projectRoot, from);
				if (fs.existsSync(source)) fs.copyFileSync(source, path.join(exportDir, to));
			}
		});
	},
};

/** 构建成功后同步到 vault 插件目录；目录未配置时静默跳过。 */
const deployToPluginDir = {
	name: "deploy-to-plugin-dir",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			deployArtifacts();
		});
	},
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: [path.join(projectRoot, "src/main.ts")],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((module) => `node:${module}`),
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: path.join(exportDir, "main.js"),
	minify: prod,
	plugins: [copyExportAssets, deployToPluginDir],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
